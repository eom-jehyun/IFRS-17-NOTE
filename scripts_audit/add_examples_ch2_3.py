def verify():
    checks = []

    def chk(label, got, want, tol=1e-5):
        checks.append((label, got, want, abs(got - want) < tol))

    v = lambda i, n: (1 + i) ** -n
    i = 0.05

    chk("d90", L[90] - L[91], 100)
    chk("d91", L[91] - L[92], 140)
    chk("l93 복원", L[90] - 100 - 140 - 200, L[93])
    chk("2p90", L[92] / L[90], 0.76)
    chk("2q90", 1 - L[92] / L[90], 0.24)
    chk("2|1q90", (L[92] - L[93]) / L[90], 0.20)
    chk("e90", sum(L[90 + k] / L[90] for k in range(1, 5)), 2.52)
    chk("0.5q90 UDD", 0.5 * 0.1, 0.05)
    chk("mu90.5", 0.1 / (1 - 0.5 * 0.1), 0.105263, 1e-6)
    chk("0.5p90 CFM", 0.9 ** 0.5, 0.948683, 1e-6)
    chk("0.5q90 CFM", 1 - 0.9 ** 0.5, 0.051317, 1e-6)
    chk("0.5p90 BA", 0.9 / (1 - 0.5 * 0.1), 0.947368, 1e-6)
    chk("0.5q90 BA", 1 - 0.9 / 0.95, 0.052632, 1e-6)
    chk("3p90", L[93] / L[90], 0.56)
    chk("v3", v(i, 3), 0.863838, 1e-6)
    chk("생존보험", v(i, 3) * L[93] / L[90], 0.483749, 1e-6)
    term = sum(v(i, k + 1) * (L[90 + k] - L[91 + k]) / L[90] for k in range(3))
    chk("정기보험", term, 0.394990, 1e-6)
    chk("생사혼합", term + v(i, 3) * L[93] / L[90], 0.878739, 1e-6)
    chk("확률합=1", (100 + 140 + 200 + 560) / 1000, 1.0)
    chk("A94", v(i, 1), 0.952381, 1e-6)
    q93 = (L[93] - L[94]) / L[93]
    p93 = L[94] / L[93]
    chk("q93", q93, 0.464286, 1e-6)
    chk("p93", p93, 0.535714, 1e-6)
    chk("A93", v(i, 1) * q93 + v(i, 1) * p93 * v(i, 1), 0.928086, 1e-6)

    bad = [c for c in checks if not c[3]]
    print(f"[수치 검증] {len(checks)}건 중 통과 {len(checks)-len(bad)}건")
    for label, got, want, ok in checks:
        if not ok:
            print(f"  ✗ {label}: 계산 {got} vs 본문 {want}")
    return not bad


def main():
    if not verify():
        print("!! 수치 불일치로 적용 중단")
        sys.exit(1)

    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)

    applied = []
    for ch in data["chapters"]:
        table = EX2 if ch["num"] == 2 else EX3 if ch["num"] == 3 else None
        if table is None:
            continue
        for part in ch["parts"]:
            for item in part["items"]:
                if item["num"] in table:
                    item["examples"] = table[item["num"]]
                    applied.append(f"Ch{ch['num']} {item['num']} {item['title']}")

    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    print(f"\n예제 추가 {len(applied)}개 항목")
    for a in applied:
        print("  ✔", a)


if __name__ == "__main__":
    main()
