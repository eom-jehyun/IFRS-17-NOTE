def main():
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)

    applied = []
    for ch in data["chapters"]:
        for part in ch.get("parts", []):
            for item in part.get("items", []):
                key = (ch["num"], item.get("num"))
                if key in P:
                    blk = item.setdefault("ifrs17", {})
                    before = blk.get("strength")
                    blk.update(P[key])
                    after = blk.get("strength")
                    mark = f" [{before} → {after}]" if before != after else ""
                    applied.append(f"Ch{key[0]} {key[1]} {item.get('title')}{mark}")

    # 나머지 항목에도 nature 기본값을 부여해 UI에서 빈칸이 생기지 않게 한다.
    filled = 0
    for ch in data["chapters"]:
        for part in ch.get("parts", []):
            for item in part.get("items", []):
                blk = item.get("ifrs17") or {}
                if not blk:
                    continue
                if "nature" not in blk:
                    s = blk.get("strength", "")
                    if s == "직접적인 수리적 기반":
                        blk["nature"] = MATH
                    elif s.startswith("직접 대응"):
                        pass  # 연결이 없으므로 nature 자체가 불필요
                    else:
                        blk["nature"] = MIXED
                    if "nature" in blk:
                        filled += 1

    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)

    print(f"명시 수정 {len(applied)}건 / 목표 {len(P)}건, nature 기본값 부여 {filled}건")
    for a in applied:
        print("  ✔", a)


if __name__ == "__main__":
    main()
